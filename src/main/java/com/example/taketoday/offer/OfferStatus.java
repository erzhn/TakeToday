package com.example.taketoday.offer;

/** Состояние предложения в базе. «Время вышло» и «Всё продано» не хранятся — их считает {@link Offer}. */
public enum OfferStatus {
    /** Выставлено на продажу. */
    ACTIVE,
    /** Снято с продажи сотрудником (п. 4.4.3 ТЗ). Можно вернуть в продажу. */
    WITHDRAWN,
    /** Скрыто администратором (п. 4.10.1 ТЗ, этап 5). Сотрудник вернуть не может. */
    HIDDEN
}
