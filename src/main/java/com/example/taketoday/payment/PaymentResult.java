package com.example.taketoday.payment;

/**
 * Что произошло после сообщения платёжной службы.
 */
public enum PaymentResult {
    /** Заказ оплачен, выдан код получения. */
    PAID,
    /** Оплата не прошла, бронь сохранена — можно попробовать ещё раз. */
    FAILED,
    /** Деньги пришли, но бронь к этому моменту уже снята — заказ отменён, деньги нужно вернуть. */
    LATE_PAYMENT,
    /** Пришли деньги за заказ, который уже оплачен другой попыткой, — вторую сумму нужно вернуть. */
    ALREADY_PAID,
    /** Повторное сообщение о той же оплате — ничего не меняли. */
    DUPLICATE
}
