package com.example.taketoday.payment;

/** Состояние одной попытки оплаты. */
public enum PaymentStatus {
    /** Покупатель на странице платёжной службы, результата ещё нет. */
    CREATED,
    /** Деньги списаны. */
    SUCCEEDED,
    /** Отказ: недостаточно средств, отмена покупателем и т. п. Можно повторить. */
    FAILED,
    /** Покупатель начал новую попытку — эта больше не действует. */
    CANCELLED
}
